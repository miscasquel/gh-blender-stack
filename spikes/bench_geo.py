import bpy, time, json, numpy as np
dg = lambda: bpy.context.evaluated_depsgraph_get()
bpy.ops.object.select_all(action="SELECT"); bpy.ops.object.delete()
bpy.ops.mesh.primitive_grid_add(x_subdivisions=224, y_subdivisions=224, size=2)
ob = bpy.context.active_object
me = ob.data
N = len(me.vertices); T = len(me.polygons)
print("B0 verts", N, "polys", T, flush=True)
t = time.perf_counter()
co = np.empty(N * 3, dtype=np.float32); me.vertices.foreach_get("co", co)
ls = np.empty(T, dtype=np.int32); me.polygons.foreach_get("loop_start", ls)
lt = np.empty(T, dtype=np.int32); me.polygons.foreach_get("loop_total", lt)
L = int(lt.sum())
loops = np.empty(L, dtype=np.int32); me.loops.foreach_get("vertex_index", loops)
print(f"B1 numpy read (verts+topology): {(time.perf_counter()-t)*1000:.1f} ms", flush=True)
t = time.perf_counter()
ev = ob.evaluated_get(dg()); m = ev.evaluated_geometry().mesh
print(f"B2 evaluated mesh access: {(time.perf_counter()-t)*1000:.1f} ms", flush=True)
t = time.perf_counter()
tmp = bpy.data.meshes.new("bench")
tmp.vertices.add(N); tmp.vertices.foreach_set("co", co)
tmp.loops.add(L); tmp.loops.foreach_set("vertex_index", loops)
tmp.polygons.add(T); tmp.polygons.foreach_set("loop_start", ls); tmp.polygons.foreach_set("loop_total", lt)
tmp.update()
print(f"B3 numpy -> mesh write (foreach_set): {(time.perf_counter()-t)*1000:.1f} ms", flush=True)
t = time.perf_counter()
tmp2 = bpy.data.meshes.new("pyd")
tmp2.from_pydata(co.reshape(-1, 3).tolist(), [], [tuple(loops[ls[i]:ls[i] + lt[i]]) for i in range(T)])
print(f"B4 from_pydata write: {(time.perf_counter()-t)*1000:.1f} ms", flush=True)
t = time.perf_counter()
payload = json.dumps({"verts": co.reshape(-1, 3).tolist(), "faces": [loops[ls[i]:ls[i] + lt[i]].tolist() for i in range(T)]})
print(f"B5 JSON encode: {(time.perf_counter()-t)*1000:.1f} ms, size {len(payload)/1e6:.1f} MB", flush=True)
blob = co.tobytes() + loops.tobytes() + ls.tobytes() + lt.tobytes()
print(f"B6 binary blob size: {len(blob)/1e6:.2f} MB, tobytes {0:.1f} ms", flush=True)
